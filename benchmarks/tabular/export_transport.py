"""Untimed transport for server-owned benchmark exports.

openGauss creates COPY output as 0600 owned by omm. A Docker bind mount does
not change that ownership. Read through the owning account, then publish a
runner-owned copy of this public-data output. Never loosen database directories
or require the benchmark runner to be root.
"""
from pathlib import Path
import subprocess


def collect_export(path: Path, container_path: str, engine: str) -> None:
    if engine != 'og':
        return
    result = subprocess.run(
        ['docker', 'exec', '-u', 'omm', 'bench-og', 'cat', '--', container_path],
        text=True, capture_output=True, timeout=180, check=True)
    # The benchmark's case directory is runner-owned and explicitly shared with
    # the database containers, so unlink does not require file read permission.
    path.unlink()
    path.write_text(result.stdout)


def install() -> None:
    """Install only the harness SQL-export hook, before invoking run.main()."""
    import run
    original = run.sql

    def sql_with_export_collection(engine, text, out=None, timeout=300):
        result = original(engine, text, out, timeout)
        # These log names are generated by run.benchmark_db, not user input.
        # Restrict collection to the exact prediction output of that call.
        if engine == 'og' and out is not None and out.name.endswith('-prediction-export.log'):
            target = out.with_name(out.name.replace('-prediction-export.log', '-predictions.csv'))
            collect_export(target, '/bench/' + out.parent.name + '/' + target.name, engine)
        return result
    run.sql = sql_with_export_collection


if __name__ == '__main__':
    install()
    import run
    run.main()
